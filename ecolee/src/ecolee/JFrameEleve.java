// Récupérer le sexe sélectionné
  private int getFiliereId() {
        String selected = jComboBox1.getSelectedItem().toString();
        for (Map.Entry<Integer, String> entry : mapFiliere.entrySet()) {
            if (entry.getValue().equals(selected)) {
                return entry.getKey();
            }
        }
        return -1; // erreur si non trouvé
    }

    // Obtenir le sexe sélectionné
    private String getSexe() {
        if (jRadioButton1.isSelected()) return "M";
        if (jRadioButton2.isSelected()) return "F";
        return "";
    }

// Vider les champs du formulaire
private void viderChamps() {
    jTextField2.setText("");
    jTextField3.setText("");
    jRadioButton1.setSelected(false);
    jRadioButton2.setSelected(false);
    jComboBox1.setSelectedIndex(0);
}

// Charger le tableau avec les élèves
private void chargerTableau() {
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);
    for (Object[] row : dao.lister()) {
        model.addRow(row);
    }
}


