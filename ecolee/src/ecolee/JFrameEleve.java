    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
     int row = jTable1.getSelectedRow();
    if (row >= 0) {
        int id = (int) jTable1.getValueAt(row, 0);
        int filiere_id = getFiliereId();
        if(filiere_id == -1) {
            JOptionPane.showMessageDialog(this, "Veuillez sélectionner une filière !");
            return;
        }
        String sexe = getSexe();
        if(sexe.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Veuillez sélectionner le sexe !");
            return;
        }
        dao.modifier(id, jTextField2.getText(), jTextField3.getText(), filiere_id, sexe);
        chargerTableau();
        viderChamps();
    } else {
        JOptionPane.showMessageDialog(this, "Sélectionnez un élève !");
    }

    }//GEN-LAST:event_jButton3ActionPerformed

