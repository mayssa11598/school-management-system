    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
    int filiere_id = getFiliereId(); // Récupère l'ID de la filière sélectionnée
    if(filiere_id == -1) {
        JOptionPane.showMessageDialog(this, "Veuillez sélectionner une filière !");
        return;
    }

    String sexe = getSexe();
    if(sexe.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Veuillez sélectionner le sexe !");
        return;
    }

    dao.ajouter(
        jTextField2.getText(), // Nom
        jTextField3.getText(), // Prenom
        filiere_id,            // ID filière
        sexe                   // Sexe
    );

    chargerTableau();
    viderChamps();

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
          int row = jTable1.getSelectedRow();
    if (row >= 0) {
        int id = (int) jTable1.getValueAt(row, 0); // ID de l'élève sélectionné
        int confirm = JOptionPane.showConfirmDialog(this, "Voulez-vous vraiment supprimer cet élève ?", 
                                                    "Confirmation", JOptionPane.YES_NO_OPTION);
        if(confirm == JOptionPane.YES_OPTION) {
            dao.supprimer(id);
            chargerTableau();
            viderChamps();
        }
    } else {
        JOptionPane.showMessageDialog(this, "Sélectionnez un élève !");
    }
    }//GEN-LAST:event_jButton2ActionPerformed

