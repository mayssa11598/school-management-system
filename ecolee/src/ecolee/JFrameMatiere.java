private void viderChamps() {
    jTextField1.setText("");
    jTextField2.setText("");
}

private void chargerTableau() {
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);
    for (Object[] row : dao.lister()) {
        model.addRow(row);
    }
}


