    private void jToggleButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton2ActionPerformed
        // TODO add your handling code here:
         int row = jTable1.getSelectedRow();
    if (row >= 0) {
        int id = (int) jTable1.getValueAt(row, 0);
        int confirm = JOptionPane.showConfirmDialog(this,
            "Voulez-vous vraiment supprimer cette matière ?", "Confirmation", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            dao.supprimer(id);
            chargerTableau();
            viderChamps();
        }
    } else {
        JOptionPane.showMessageDialog(this, "Sélectionnez une matière !");
    }
    }//GEN-LAST:event_jToggleButton2ActionPerformed

    private void jToggleButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton3ActionPerformed
        // TODO add your handling code here:
     int row = jTable1.getSelectedRow();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Sélectionnez une matière !");
        return;
    }

    int id = (int) jTable1.getValueAt(row, 0);
    String nom = jTextField1.getText().trim();
    if (nom.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Veuillez saisir le nom de la matière !");
        return;
    }

    double coeff;
    try {
        coeff = Double.parseDouble(jTextField2.getText().trim());
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Coefficient invalide !");
        return;
    }

    // Appel DAO pour modifier
    dao.modifier(id, nom, coeff);

    // Recharge le tableau
    chargerTableau();

    // Vide les champs
    viderChamps();


    }//GEN-LAST:event_jToggleButton3ActionPerformed

