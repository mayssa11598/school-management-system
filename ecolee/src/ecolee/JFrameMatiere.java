    private void jToggleButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton1ActionPerformed
        // TODO add your handling code here:
        String nom = jTextField1.getText().trim();
    if (nom.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Veuillez saisir le nom de la matière !");
        return;
    }

    double coeff;
    try {
        coeff = Double.parseDouble(jTextField2.getText().trim());
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Coefficient invalide !");
        return;
    }

    // Appel DAO pour ajouter la matière
    dao.ajouter(nom, coeff);

    // Recharge le tableau
    chargerTableau();

    // Vide les champs
    viderChamps();

    }//GEN-LAST:event_jToggleButton1ActionPerformed

